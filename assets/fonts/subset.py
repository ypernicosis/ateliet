#!/usr/bin/env python3
"""Regenerate Lucide.ttf (a subset of Lucide's icon font) and src/icons.rs.

    pip install fonttools
    npm pack lucide-static@0.469.0 && tar xzf lucide-static-0.469.0.tgz
    python3 subset.py package/font

Icons are listed in lucide-icons.txt (Lucide names, whitespace separated).
"""
import json, os, re, subprocess, sys

here = os.path.dirname(os.path.abspath(__file__))
font_dir = sys.argv[1]
info = json.load(open(os.path.join(font_dir, 'info.json')))
names = open(os.path.join(here, 'lucide-icons.txt')).read().split()
missing = [n for n in names if n not in info]
if missing:
    sys.exit('not in Lucide: ' + ', '.join(missing))
codes = [(n, int(info[n]['encodedCode'][1:], 16)) for n in names]
subprocess.check_call(['pyftsubset', os.path.join(font_dir, 'lucide.ttf'), '--unicodes=' + ','.join('U+%04X' % c for _, c in codes), '--output-file=' + os.path.join(here, 'Lucide.ttf')])
out = ['//! Lucide icons (ISC licence), drawn from a subset of its icon font.', '//! Generated by `assets/fonts/subset.py`; add names to', '//! `lucide-icons.txt` and run it again.', '#![allow(dead_code)]', '']
out += ['pub const %s: &str = "\\u{%04x}";' % (re.sub(r'[^A-Z0-9]', '_', n.upper()), c) for n, c in codes]
open(os.path.join(here, '..', '..', 'src', 'icons.rs'), 'w').write('\n'.join(out) + '\n')
print(len(codes), 'icons')
